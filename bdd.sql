-- --------------------------------------------------------------------------
-- Paramètres du tournoi (une seule ligne, id = 1)
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS event (
  id                 SMALLINT     NOT NULL CHECK (id >= 0),
  registrations_open SMALLINT     NOT NULL DEFAULT 1 CHECK (registrations_open IN (0, 1)),
  "date"             VARCHAR(100) NOT NULL DEFAULT '',
  venue              VARCHAR(150) NOT NULL DEFAULT '',
  price              VARCHAR(60)  NOT NULL DEFAULT '',
  bts1_tagline       VARCHAR(60)  NOT NULL DEFAULT 'Les challengers',      -- slogan affiché sous « BTS 1 »
  bts2_tagline       VARCHAR(60)  NOT NULL DEFAULT 'Les tenants du titre', -- slogan affiché sous « BTS 2 »
  PRIMARY KEY (id)
);

-- Bases créées avant l'ajout des slogans
ALTER TABLE event ADD COLUMN IF NOT EXISTS bts1_tagline VARCHAR(60) NOT NULL DEFAULT 'Les challengers';
ALTER TABLE event ADD COLUMN IF NOT EXISTS bts2_tagline VARCHAR(60) NOT NULL DEFAULT 'Les tenants du titre';

INSERT INTO event (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- --------------------------------------------------------------------------
-- Équipes
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS teams (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
  name         VARCHAR(30) NOT NULL,
  promo        VARCHAR(5)  NOT NULL CHECK (promo IN ('BTS 1', 'BTS 2')),
  code         VARCHAR(12) NOT NULL,                 -- code d'invitation (6 caractères), public
  manage_token VARCHAR(40) NOT NULL,                 -- lien secret du capitaine (modération)
  max_players  SMALLINT    NOT NULL CHECK (max_players >= 0), -- entre 5 et 8
  closed       SMALLINT    NOT NULL DEFAULT 0 CHECK (closed IN (0, 1)),
  created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT teams_code UNIQUE (code),
  CONSTRAINT teams_manage_token UNIQUE (manage_token)
);

-- nom unique par promotion, sans tenir compte de la casse
CREATE UNIQUE INDEX IF NOT EXISTS teams_name_promo ON teams (LOWER(name), promo);

-- --------------------------------------------------------------------------
-- Participants
-- status : pre_registered = inscrit / accepté · pending = demande en attente du capitaine
--          rejected = refusé par le capitaine · cancelled = annulé par le BDE
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS participants (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
  first_name  VARCHAR(60)  NOT NULL,
  last_name   VARCHAR(60)  NOT NULL,
  promo       VARCHAR(5)   NOT NULL CHECK (promo IN ('BTS 1', 'BTS 2')),
  class_name  VARCHAR(40)  NOT NULL DEFAULT '',
  level       VARCHAR(20)  NOT NULL DEFAULT ''
              CHECK (level IN ('', 'Loisir', 'Intermédiaire', 'Compétition')),
  contact     VARCHAR(120) NOT NULL DEFAULT '',
  mode        VARCHAR(20)  NOT NULL CHECK (mode IN ('solo', 'captain', 'team_member')),
  team_id     INTEGER      NULL,                     -- NULL = solo, à affecter par le BDE
  status      VARCHAR(20)  NOT NULL DEFAULT 'pre_registered'
              CHECK (status IN ('pre_registered', 'pending', 'rejected', 'cancelled')),
  track_token VARCHAR(40)  NULL,                     -- lien de suivi de la demande par le joueur
  consent_at  TIMESTAMP    NOT NULL,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT participants_track_token UNIQUE (track_token),
  CONSTRAINT fk_participants_team FOREIGN KEY (team_id) REFERENCES teams (id)
);

CREATE INDEX IF NOT EXISTS participants_team ON participants (team_id);
